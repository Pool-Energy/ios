import Foundation

enum APIError: LocalizedError {
    case invalidURL
    case http(Int)
    case decoding(Error)
    case transport(Error)

    var errorDescription: String? {
        switch self {
        case .invalidURL:
            return "Invalid API URL"
        case .http(let code):
            if code == 429 {
                return "Too many requests — the public API is rate limited, try again in a few minutes."
            }
            return "The API answered with HTTP \(code)"
        case .decoding:
            return "Unexpected response format"
        case .transport(let error):
            return error.localizedDescription
        }
    }
}

struct APIClient {
    static let shared = APIClient()

    let baseURL: URL
    private let session: URLSession
    private let cache = ResponseCache.shared

    /// Short-lived cache used to collapse the bursts generated by tab switches
    /// and live refreshes.
    private let cacheTTL: TimeInterval = 5

    init(baseURL: URL = URL(string: "https://pool.energy/api/v1.0/")!) {
        self.baseURL = baseURL
        let configuration = URLSessionConfiguration.default
        configuration.timeoutIntervalForRequest = 20
        configuration.waitsForConnectivity = true
        configuration.requestCachePolicy = .reloadIgnoringLocalCacheData
        self.session = URLSession(configuration: configuration)
    }

    // MARK: Public

    func get<T: Decodable>(_ path: String, query: [String: String] = [:], ttl: TimeInterval? = nil) async throws -> T {
        try await request(url(for: path, query: query), ttl: ttl ?? cacheTTL)
    }

    func page<T: Decodable>(_ path: String, query: [String: String] = [:], ttl: TimeInterval? = nil) async throws -> Page<T> {
        try await request(url(for: path, query: query), ttl: ttl ?? cacheTTL)
    }

    func page<T: Decodable>(from urlString: String) async throws -> Page<T> {
        guard let url = URL(string: urlString) else { throw APIError.invalidURL }
        // Paginated links are one-shot: no point caching them.
        return try await request(url, ttl: 0)
    }

    // MARK: Private

    private func url(for path: String, query: [String: String]) -> URL {
        let base = baseURL.absoluteString + path
        guard var components = URLComponents(string: base) else { return baseURL }
        if !query.isEmpty {
            components.queryItems = query
                .sorted { $0.key < $1.key }
                .map { URLQueryItem(name: $0.key, value: $0.value) }
        }
        return components.url ?? baseURL
    }

    private func request<T: Decodable>(_ url: URL, ttl: TimeInterval) async throws -> T {
        let data = try await cache.data(for: url, ttl: ttl) {
            try await self.load(url)
        }

        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        do {
            return try decoder.decode(T.self, from: data)
        } catch {
            throw APIError.decoding(error)
        }
    }

    /// Performs the request, retrying once when the API rate limits us so a
    /// short burst does not surface as an error to the user.
    private func load(_ url: URL, attempt: Int = 0) async throws -> Data {
        var request = URLRequest(url: url)
        request.cachePolicy = .reloadIgnoringLocalCacheData
        request.setValue("application/json", forHTTPHeaderField: "Accept")

        await RequestGate.shared.acquire()
        let data: Data
        let response: URLResponse
        do {
            (data, response) = try await session.data(for: request)
        } catch {
            await RequestGate.shared.release()
            throw APIError.transport(error)
        }
        await RequestGate.shared.release()

        guard let http = response as? HTTPURLResponse else { return data }

        if http.statusCode == 429, attempt < 4, let delay = Self.retryDelay(from: http, attempt: attempt) {
            try? await Task.sleep(nanoseconds: UInt64(delay * 1_000_000_000))
            return try await load(url, attempt: attempt + 1)
        }

        if !(200..<300).contains(http.statusCode) {
            throw APIError.http(http.statusCode)
        }
        return data
    }

    private static func retryDelay(from response: HTTPURLResponse, attempt: Int) -> TimeInterval? {
        if let value = response.value(forHTTPHeaderField: "Retry-After"),
           let seconds = TimeInterval(value) {
            // Wait for short windows; for longer ones, back off a few times
            // before surfacing the error instead of freezing the UI for minutes.
            return min(seconds, 10)
        }
        return TimeInterval(2 << attempt)
    }
}
